import { StatusCodes } from "http-status-codes";
import {
  customErrorResponse,
  internalErrorResponse,
  successResponse
} from "../utils/common/responseObject.js";
import {
  addChannelToWorkspaceService,
  addMemberToWorkspaceService,
  createWorkspaceService,
  deleteWorkspaceService,
  getWorkspaceByJoinCodeService,
  getWorkspaceService,
  getWorkspaceUserIsMemberOfService,
  updateWorkspaceService
} from "../services/workspaceService.js";

export const createWorkspaceController = async (req, res) => {
  try {
    const response = await createWorkspaceService({
      ...req.body,
      owner: req.user
    });
    return res
      .status(StatusCodes.CREATED)
      .json(successResponse(response, "workspace created successfully"));
  } catch (error) {
    console.log(error);
    if (error.statusCode) {
      return res.status(error.statusCode).json(customErrorResponse(error));
    }
    return res
      .status(StatusCodes.INTERNAL_SERVER_ERROR)
      .json(internalErrorResponse(error));
  }
};

export const getWorkspaceUserIsMemberOfController = async (req, res) => {
  try {
    const userId = req.user;
    const workspaces = await getWorkspaceUserIsMemberOfService(userId);

    return res
      .status(StatusCodes.OK)
      .json(
        successResponse(
          workspaces,
          "workspaces user is member of is fetched successfully"
        )
      );
  } catch (error) {
    console.log(error);
    return res
      .status(StatusCodes.INTERNAL_SERVER_ERROR)
      .json(internalErrorResponse(error));
  }
};

